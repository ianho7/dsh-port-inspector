import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { basename, dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = resolve(repositoryRoot, 'assets/toolchains/sources.json')
const assetDirectory = resolve(repositoryRoot, 'assets/toolchains')
const outputPath = resolve(repositoryRoot, 'src/client/toolchain-logo-data.ts')
const maximumAssetBytes = 256 * 1024
const mimeByExtension = new Map([
  ['.svg', 'image/svg+xml'],
  ['.png', 'image/png'],
  ['.ico', 'image/x-icon'],
])
const extensionByMime = new Map([...mimeByExtension].map(([extension, mime]) => [mime, extension]))
extensionByMime.set('image/vnd.microsoft.icon', '.ico')

export function validateSource(assetUrl) {
  const source = new URL(assetUrl)
  if (source.protocol !== 'https:') throw new Error('Logo sources must use HTTPS.')
  return source.href
}

export function sanitizeSvg(svg) {
  if (!/<svg(?:\s|>)/iu.test(svg)) throw new Error('SVG payload has no root svg element.')
  if (/<(?:script|foreignObject|iframe|object|embed)(?:\s|>)/iu.test(svg)) throw new Error('SVG payload contains active content.')
  if (/<!(?:DOCTYPE|ENTITY)\b|<\?xml-stylesheet\b/iu.test(svg)) throw new Error('SVG payload contains external XML content.')
  if (/@import\b/iu.test(svg)) throw new Error('SVG payload contains active styling content.')
  if (/\son[a-z]+\s*=/iu.test(svg)) throw new Error('SVG payload contains an event handler.')
  if (/\burl\s*\(\s*["']?(?:https?:|\/\/|data:text|javascript:)/iu.test(svg)
    || /\b(?:href|src)\s*=\s*["'](?!#|data:image\/)/iu.test(svg)) throw new Error('SVG payload contains an external reference.')
  return svg.replace(/<\?xml[^>]*>/giu, '').trim()
}

async function localAssets() {
  const assets = new Map()
  for (const file of (await readdir(assetDirectory)).sort()) {
    const extension = extname(file).toLowerCase()
    const mime = mimeByExtension.get(extension)
    if (mime === undefined) continue
    const id = file.slice(0, -extension.length)
    if (assets.has(id)) throw new Error(`${id}: multiple local logo files found.`)
    assets.set(id, { path: join(assetDirectory, file), mime })
  }
  return assets
}

async function readBoundedBytes(response, id) {
  const contentLength = Number(response.headers.get('content-length'))
  if (Number.isFinite(contentLength) && contentLength > maximumAssetBytes) {
    throw new Error(`${id}: asset exceeds ${maximumAssetBytes} bytes.`)
  }
  if (response.body?.getReader === undefined) {
    const bytes = new Uint8Array(await response.arrayBuffer())
    if (bytes.byteLength > maximumAssetBytes) throw new Error(`${id}: asset exceeds ${maximumAssetBytes} bytes.`)
    return bytes
  }
  const reader = response.body.getReader()
  const chunks = []
  let total = 0
  try {
    while (true) {
      const next = await reader.read()
      if (next.done) break
      total += next.value.byteLength
      if (total > maximumAssetBytes) {
        await reader.cancel()
        throw new Error(`${id}: asset exceeds ${maximumAssetBytes} bytes.`)
      }
      chunks.push(next.value)
    }
  } finally {
    reader.releaseLock()
  }
  const bytes = new Uint8Array(total)
  let offset = 0
  for (const chunk of chunks) {
    bytes.set(chunk, offset)
    offset += chunk.byteLength
  }
  return bytes
}

async function fetchAsset(id, assetUrl, fetchImpl, existingAsset) {
  const response = await fetchImpl(validateSource(assetUrl), { redirect: 'error' })
  if (!response.ok) throw new Error(`${id}: download failed with ${response.status}.`)
  const mime = (response.headers.get('content-type') ?? '').split(';', 1)[0].trim().toLowerCase()
  const extension = extensionByMime.get(mime)
  if (extension === undefined) throw new Error(`${id}: unsupported MIME ${mime || '(missing)'}.`)
  let bytes = await readBoundedBytes(response, id)
  if (mime === 'image/svg+xml') bytes = new TextEncoder().encode(sanitizeSvg(new TextDecoder().decode(bytes)))
  const path = existingAsset?.path ?? join(assetDirectory, `${id}${extension}`)
  await writeFile(path, bytes)
  return { path, mime }
}

function importIdentifier(id) {
  return `toolchainLogo${id.split('-').map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join('')}`
}

async function writeGeneratedSource(assets) {
  const entries = [...assets.entries()].sort(([left], [right]) => left.localeCompare(right))
  const imports = entries.map(([id, asset]) => {
    const file = basename(asset.path)
    return `import ${importIdentifier(id)} from 'toolchain-assets/${file}'`
  })
  const values = entries.map(([id]) => `  ${JSON.stringify(id)}: ${importIdentifier(id)}`)
  const source = [
    '// Generated by scripts/update-toolchain-logos.mjs from assets/toolchains; do not edit by hand.',
    ...imports,
    '',
    'export const TOOLCHAIN_LOGO_DATA = {',
    `${values.join(',\n')}`,
    '} as const',
    '',
  ].join('\n')
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, source, 'utf8')
}

export async function updateToolchainLogos({ fetchImpl = fetch, refresh = false } = {}) {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
  await mkdir(assetDirectory, { recursive: true })
  const assets = await localAssets()
  for (const [id, assetUrl] of Object.entries(manifest)) {
    if (typeof assetUrl !== 'string') throw new Error(`${id}: source must be a URL string.`)
    if (assets.has(id) && !refresh) continue
    const asset = await fetchAsset(id, assetUrl, fetchImpl, assets.get(id))
    assets.set(id, asset)
  }
  await writeGeneratedSource(assets)
  return assets
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await updateToolchainLogos({ refresh: process.argv.includes('--refresh') })
}
